BOOK_NOTICE = 'Краткие ориентиры и вопросы, не полный текст книги и не официальное издание АА.'


def overview(kind: str) -> tuple[str, dict]:
    prayers = kind == 'prayers'
    titles = PRAYER_TITLES if prayers else BOOK_TITLES
    prefix = 'p:' if prayers else 'bk:'
    title = '🙏 Молитвы' if prayers else '📘 Большая книга'
    notice = PRAYER_NOTICE if prayers else BOOK_NOTICE
    rows = [[{'text': text, 'callback_data': prefix + key}] for key, text in titles.items()]
    return f'<b>{title}</b>\n\n{notice}', {'inline_keyboard': rows}


def item(data: str) -> tuple[str, dict]:
    prayers = data.startswith('p:')
    key = data.split(':', 1)[1]
    content = PRAYERS if prayers else BK
    notice = PRAYER_NOTICE if prayers else BOOK_NOTICE
    back = 'library:prayers' if prayers else 'library:book'
    text = content.get(key, 'Раздел не найден. Выбери его в меню.')
    return text + '\n\n<i>' + notice + '</i>', {
        'inline_keyboard': [[{'text': '← К списку', 'callback_data': back}]]
    }
